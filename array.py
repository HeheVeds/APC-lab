#for 'b' typecode
from array import array

a = array('b', [10, 20, 30, 20])

print("Original:", a)

a.append(40)
print("Append:", a)

a.insert(1, 15)
print("Insert:", a)

a.remove(20)
print("Remove:", a)

a.pop()
print("Pop:", a)

print("Count of 20:", a.count(20))

a.extend([50, 60])
print("Extend:", a)

print("Index of 30:", a.index(30))

a.reverse()
print("Reverse:", a)


